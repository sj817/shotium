const dictionaries: Record<Locale, Record<MessageKey, string>> = {'zh-CN': zh, en};

export type Params = Record<string, string | number>;

export function resolveLocale(lang: string | null | undefined): Locale {
  return lang && lang.toLowerCase().startsWith('en') ? 'en' : 'zh-CN';
}

export function hasMessage(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(zh, key);
}

export function translate(locale: Locale, key: MessageKey, params?: Params): string {
  const template = dictionaries[locale][key] ?? zh[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match);
}

export interface Segment {
  text: string;
  param: string | null;
}

/** Like translate(), but keeps each substituted parameter as its own segment so it can be emphasised. */
export function segments(locale: Locale, key: MessageKey, params: Params): Segment[] {
  const template = dictionaries[locale][key] ?? zh[key];
  const out: Segment[] = [];
  const pattern = /\{(\w+)\}/g;
  let last = 0;
  for (const match of template.matchAll(pattern)) {
    const name = match[1] ?? '';
    const start = match.index ?? 0;
    if (start > last) out.push({text: template.slice(last, start), param: null});
    if (Object.prototype.hasOwnProperty.call(params, name)) {
      out.push({text: String(params[name]), param: name});
    } else {
      out.push({text: match[0], param: null});
    }
    last = start + match[0].length;
  }
  if (last < template.length) out.push({text: template.slice(last), param: null});
  return out;
}
